"""
Задание 1: Функция генерации чисел Фибоначчи.
Задача 1: Написать функцию fib(n), возвращающую список первых n чисел Фибоначчи.
Задание «со звёздочкой»: Реализовать функцию-генератор с yield.
"""


def fib(n):
    """
    Возвращает список первых n чисел последовательности Фибоначчи.

    Args:
        n (int): Количество чисел для генерации.

    Returns:
        list: Список из n чисел Фибоначчи.
    """
    if n <= 0:
        return []
    elif n == 1:
        return [0]
    elif n == 2:
        return [0, 1]

    result = [0, 1]
    for i in range(2, n):
        result.append(result[-1] + result[-2])
    return result


def fib_generator(n):
    """
    Генератор, возвращающий числа Фибоначчи по одному.

    Args:
        n (int): Количество чисел для генерации.

    Yields:
        int: Следующее число Фибоначчи.
    """
    a, b = 0, 1
    count = 0
    while count < n:
        yield a
        a, b = b, a + b
        count += 1


